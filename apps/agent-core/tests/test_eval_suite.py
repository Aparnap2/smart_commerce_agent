"""
Pattern 14: Eval Test Suite - LLM-as-judge evaluation for agent responses

Implements binary (pass/fail) scoring for ProcureAI agent behaviors.
Tests cover the 6 failure modes identified in the book.
"""
import pytest
from src.eval_suite import EVAL_CASES, evaluate_response


class TestEvalSuite:
    """Test evaluation suite for ProcureAI agent."""

    def test_eval_cases_exist(self):
        """Should have 10 evaluation cases."""
        assert len(EVAL_CASES) == 10

    def test_employee_cannot_approve(self):
        """Failure mode: Wrong tool selection - EMPLOYEE tries process_approval."""
        case = next(c for c in EVAL_CASES if c["name"] == "employee_approval_attempt")
        # Test that EMPLOYEE calling process_approval is blocked
        result = evaluate_response(
            user_input=case["input"],
            role="EMPLOYEE",
            tool_calls=[{"name": "process_approval", "args": {"pr_id": "PR-001"}}],
        )
        # Should FAIL because EMPLOYEE cannot call process_approval
        assert result["passed"] is False
        assert result["failure_mode"] == "wrong_tool_selection"

    def test_budget_exceeded_blocks_submission(self):
        """Failure mode: Budget hallucination - should block over-budget PR."""
        case = next(c for c in EVAL_CASES if c["name"] == "over_budget_submission")
        result = evaluate_response(
            user_input=case["input"],
            role=case["role"],
            tool_calls=[{"name": "submit_for_approval", "args": {}}],
            budget_status={"remaining": 50000, "total": 100000}
        )
        assert result["passed"] is False  # Should fail - over budget should block

    def test_pr_creation_unique_id(self):
        """Failure mode: PR number collision - should generate unique IDs."""
        # PR creation should succeed with unique IDs (implemented via DB sequence)
        pr1_result = evaluate_response(
            user_input="Create PR for laptop",
            role="EMPLOYEE",
            tool_calls=[{"name": "manage_purchase_request", "args": {"action": "create"}}],
            expected_outcome="pr_created"
        )
        pr2_result = evaluate_response(
            user_input="Create PR for monitor",
            role="EMPLOYEE",
            tool_calls=[{"name": "manage_purchase_request", "args": {"action": "create"}}],
            expected_outcome="pr_created"
        )
        
        # Both should pass - unique IDs are generated by DB
        assert pr1_result["passed"] is True
        assert pr2_result["passed"] is True

    def test_hitl_thread_saved_to_db(self):
        """Failure mode: HITL thread lost - thread ID should be persisted."""
        case = next(c for c in EVAL_CASES if c["name"] == "submit_triggers_approval")
        
        result = evaluate_response(
            user_input=case["input"],
            role=case["role"],
            tool_calls=[{"name": "submit_for_approval", "args": {"pr_id": "PR-001"}}],
            thread_saved_to_db=True
        )
        assert result["passed"] is True

    def test_genui_price_not_null(self):
        """Failure mode: GenUI null crash - price should never be undefined."""
        result = evaluate_response(
            user_input="show laptops",
            role="EMPLOYEE",
            tool_calls=[{"name": "search_catalog", "args": {"query": "laptop"}}],
            ui_response={"products": [{"name": "MacBook", "price": None}]}
        )
        # Should detect null price as failure
        assert result["passed"] is False

    def test_context_uses_correct_items(self):
        """Test that employee can add items to cart."""
        # This test verifies normal flow - adding item should work
        result = evaluate_response(
            user_input="add Dell XPS to PR",
            role="EMPLOYEE",
            tool_calls=[{"name": "manage_purchase_request", "args": {"action": "add_item", "catalog_item_id": "dell-xps"}}],
        )
        # Should pass - item added successfully
        assert result["passed"] is True

    def test_finance_role_restricted_tools(self):
        """FINANCE role should not have submit/approve tools."""
        case = next(c for c in EVAL_CASES if c["name"] == "finance_role_restrictions")
        
        tools = case["expected_tools"]
        assert "submit_for_approval" not in tools
        assert "process_approval" not in tools

    def test_employee_sees_catalog(self):
        """EMPLOYEE should see search_catalog in available tools."""
        case = next(c for c in EVAL_CASES if c["name"] == "employee_search")
        
        result = evaluate_response(
            user_input=case["input"],
            role=case["role"],
            tool_calls=[{"name": "search_catalog"}]
        )
        assert result["passed"] is True

    def test_budget_check_before_large_purchase(self):
        """Should check budget before large purchase (> 50% of budget)."""
        case = next(c for c in EVAL_CASES if c["name"] == "budget_check_large")
        
        result = evaluate_response(
            user_input=case["input"],
            role=case["role"],
            tool_calls=[{"name": "get_budget_status"}],
            budget_status={"remaining": 100000, "total": 500000}
        )
        assert result["passed"] is True  # Should check budget first

    def test_manager_can_approve(self):
        """MANAGER role should have process_approval tool."""
        case = next(c for c in EVAL_CASES if c["name"] == "manager_approval")
        
        result = evaluate_response(
            user_input=case["input"],
            role=case["role"],
            tool_calls=[{"name": "process_approval", "args": {"pr_id": "PR-001", "decision": "APPROVED"}}],
        )
        assert result["passed"] is True